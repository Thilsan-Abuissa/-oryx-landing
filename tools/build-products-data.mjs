/* =============================================================
   products.json  ->  assets/js/products-data.js

   products.json is the source of truth; the page fetches it. But a
   browser refuses to fetch a file:// URL (CORS), so opening
   products.html straight off the disk would show nothing. This writes
   the same array out as a plain script the page can fall back to.

   It also writes the catalogue's structured data into products.html,
   between the SEO:products markers. The cards are built by JavaScript,
   so without this a crawler that does not run the page sees an empty
   grid; the JSON-LD states the catalogue in the HTML itself.

   Run after editing products.json:
       node tools/build-products-data.mjs
   ============================================================= */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const products = JSON.parse(readFileSync(join(root, 'products.json'), 'utf8'));

const out = join(root, 'assets/js/products-data.js');
writeFileSync(out,
  '/* GENERATED FILE — do not edit.\n' +
  '   Source: products.json. Rebuild: node tools/build-products-data.mjs\n' +
  '   Only used when the page is opened over file://, where fetch is blocked. */\n' +
  'window.PRODUCTS = ' + JSON.stringify(products, null, 2) + ';\n',
  'utf8');

console.log(products.length + ' products -> assets/js/products-data.js');


/* ---------- structured data for products.html ---------- */
const SITE = 'https://www.careplus.qa';

const graph = {
  '@context': 'https://schema.org',
  '@graph': [
    {
      '@type': 'BreadcrumbList',
      itemListElement: [
        { '@type': 'ListItem', position: 1, name: 'Home', item: SITE + '/' },
        { '@type': 'ListItem', position: 2, name: 'Products', item: SITE + '/products' }
      ]
    },
    {
      '@type': 'CollectionPage',
      '@id': SITE + '/products#page',
      url: SITE + '/products',
      name: 'Product Catalogue',
      isPartOf: { '@id': SITE + '/#website' },
      about: { '@id': SITE + '/#business' },
      inLanguage: ['en', 'ar'],
      mainEntity: {
        '@type': 'ItemList',
        name: 'CarePlus product catalogue',
        numberOfItems: products.length,
        itemListOrder: 'https://schema.org/ItemListOrderAscending',
        /* no price and no per-product page, so each entry carries what is
           actually true of it and nothing more — a fabricated offer would
           fail validation and misrepresent an enquiry-only catalogue */
        itemListElement: products.map((p, i) => ({
          '@type': 'ListItem',
          position: i + 1,
          item: {
            '@type': 'Product',
            name: p.title,
            description: p.description,
            category: p.category,
            image: SITE + '/assets/img/product-img/' + p.image_url,
            seller: { '@id': SITE + '/#business' }
          }
        }))
      }
    }
  ]
};

const page = join(root, 'products.html');
const html = readFileSync(page, 'utf8');
const START = '<!-- SEO:products:start — generated by tools/build-products-data.mjs, do not edit -->';
const END   = '<!-- SEO:products:end -->';
const a = html.indexOf(START), b = html.indexOf(END);
if (a === -1 || b === -1) throw new Error('SEO:products markers missing from products.html');

writeFileSync(page,
  html.slice(0, a + START.length) +
  '\n<script type="application/ld+json">\n' +
  JSON.stringify(graph, null, 2) +
  '\n</script>\n' +
  html.slice(b), 'utf8');

console.log(products.length + ' products -> products.html structured data');
